def upsert_farm(con, farm: dict) -> None:
    # 구버전은 INSERT OR REPLACE 였다. PostgreSQL 에 없는 문법이라
    # 양쪽에서 동작하는 ON CONFLICT DO UPDATE 로 바꿨다.
    con.execute(
        "INSERT INTO farm_config(farm_id, name, lat, lon, facility_type, "
        "last_manure_removal_date) VALUES(?,?,?,?,?,?) "
        "ON CONFLICT(farm_id) DO UPDATE SET "
        "name=excluded.name, lat=excluded.lat, lon=excluded.lon, "
        "facility_type=excluded.facility_type, "
        "last_manure_removal_date=excluded.last_manure_removal_date",
        (farm["farm_id"], farm["name"], farm["lat"], farm["lon"],
         farm["facility_type"], farm["last_manure_removal_date"]),
    )
    con.commit()
