# ── PostgreSQL 어댑터 ─────────────────────────────────────────────
def _translate(sql: str) -> str:
    """물음표 자리표시자를 psycopg 형식으로. 문자열 리터럴 안은 건드리지 않는다.

    psycopg 는 파라미터가 있을 때 퍼센트를 형식문자로 해석하므로 함께
    이스케이프한다. 이 함수는 파라미터가 있는 쿼리에만 쓴다.
    """
    out, in_str = [], False
    for ch in sql:
        if ch == "'":
            in_str = not in_str
            out.append(ch)
        elif in_str:
            out.append(ch)
        elif ch == "?":
            out.append("%s")
        elif ch == "%":
            out.append("%%")
        else:
            out.append(ch)
    return "".join(out)


def _clean(params):
    """numpy 스칼라를 파이썬 기본형으로. psycopg 에는 np.float64 어댑터가 없다."""
    if params is None:
        return None
    out = []
    for p in params:
        if type(p).__module__.split(".")[0] == "numpy" and hasattr(p, "item"):
            p = p.item()
        out.append(p)
    return tuple(out)


class _PgCursor:
    """psycopg 커서에 자리표시자 번역만 얹은 껍데기. 나머지는 그대로 위임."""

    def __init__(self, raw):
        self._raw = raw

    def execute(self, sql, params=None):
        if params:
            self._raw.execute(_translate(sql), _clean(params))
        else:
            self._raw.execute(sql)
        return self

    def executemany(self, sql, seq):
        seq = [_clean(p) for p in seq]
        if seq:
            self._raw.executemany(_translate(sql), seq)
        return self

    def fetchone(self):
        return self._raw.fetchone()

    def fetchall(self):
        return self._raw.fetchall()

    def fetchmany(self, size=None):
        return self._raw.fetchmany(size) if size else self._raw.fetchmany()

    def close(self):
        self._raw.close()

    def __iter__(self):
        return iter(self._raw)

    @property
    def description(self):
        return self._raw.description

    @property
    def rowcount(self):
        return self._raw.rowcount


class PgConnection:
    """sqlite3.Connection 처럼 보이는 PostgreSQL 커넥션.

    sqlite3 는 Connection 에도 execute/executemany 가 있지만 psycopg 는
    커서에만 있다. 호출부(특히 수정 금지인 agents/)가 con.execute(...) 를
    쓰므로 여기서 메꾼다.
    """

    def __init__(self, raw):
        self._raw = raw

    def execute(self, sql, params=None):
        return _PgCursor(self._raw.cursor()).execute(sql, params)

    def executemany(self, sql, seq):
        return _PgCursor(self._raw.cursor()).executemany(sql, seq)

    def executescript(self, sql: str):
        """sqlite3 전용 메서드의 대체. psycopg 는 파라미터 없는 다중문을 허용한다."""
        with self._raw.cursor() as cur:
            cur.execute(sql)
        self._raw.commit()
        return self

    def cursor(self):
        return _PgCursor(self._raw.cursor())

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self._raw.close()

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        if exc[0] is None:
            self._raw.commit()
        else:
            self._raw.rollback()
        return False


_PG_DDL_DONE = False


def _connect_postgres() -> PgConnection:
    global _PG_DDL_DONE
    import psycopg     # requirements: psycopg[binary]

    # prepare_threshold=None 이 필요한 이유 — Supabase 의 트랜잭션 풀러(pgbouncer,
    #   6543 포트)는 서버측 prepared statement 를 지원하지 않는다. psycopg3 는
    #   같은 쿼리를 5회 실행하면 자동으로 prepare 로 바꾸므로, 끄지 않으면
    #   매일 잘 돌던 잡이 어느 순간 DuplicatePreparedStatement 로 죽는다.
    con = psycopg.connect(DATABASE_URL, prepare_threshold=None,
                          connect_timeout=15,
                          application_name="smart-livestock-ai")
    wrapped = PgConnection(con)
    if not _PG_DDL_DONE:
        wrapped.executescript(DDL_POSTGRES)   # CREATE TABLE IF NOT EXISTS 라 멱등
        _PG_DDL_DONE = True
    return wrapped


def connect():
    """백엔드에 맞는 커넥션을 돌려준다. 호출부는 어느 쪽인지 몰라도 된다."""
    if DB_BACKEND == "postgres":
        return _connect_postgres()
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(DB_PATH)
    con.executescript(DDL_SQLITE)
    return con


def backend() -> str:
    return DB_BACKEND


def describe() -> str:
    """로그용 한 줄. 접속 문자열의 비밀번호는 절대 찍지 않는다."""
    if DB_BACKEND != "postgres":
        return f"SQLite {DB_PATH}"
    host = DATABASE_URL.rsplit("@", 1)[-1] if "@" in DATABASE_URL else "?"
    return f"PostgreSQL {host}"


def primary_key_columns(con, table: str) -> list[str]:
    """PK 컬럼명을 순서대로. run_check 의 스키마 검증이 쓴다 (백엔드 중립)."""
    if DB_BACKEND == "postgres":
        rows = con.execute(
            "SELECT a.attname FROM pg_index i "
            "JOIN pg_attribute a ON a.attrelid = i.indrelid "
            "                   AND a.attnum = ANY(i.indkey) "
            "WHERE i.indrelid = ?::regclass AND i.indisprimary "
            "ORDER BY array_position(i.indkey, a.attnum)", (table,)).fetchall()
        return [r[0] for r in rows]
    rows = con.execute(f"PRAGMA table_info({table})").fetchall()
    return [r[1] for r in sorted((r for r in rows if r[5]), key=lambda r: r[5])]


def fetch_frame(con, sql: str, params=None):
    """SELECT 결과를 DataFrame 으로. pandas.read_sql 은 백엔드마다 경고가 달라 직접 만든다."""
    import pandas as pd
    cur = con.execute(sql, params) if params else con.execute(sql)
    rows = cur.fetchall()
    cols = [c[0] for c in cur.description]
    return pd.DataFrame(rows, columns=cols)


