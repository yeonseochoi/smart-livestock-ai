TIME_WEIGHTS = (0.30, 0.22, 0.17, 0.13, 0.10, 0.08)


def storage_factor(days: int | None) -> float:
    """기존 S5 정책: 14일 미만 1.0, 14일 이상 1.5 [C]."""

    if days is None:
        return 1.0
    return 1.0 if days < 14 else 1.5
