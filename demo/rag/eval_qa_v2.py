def run(index, boost: bool = True) -> dict:
    hits, details = 0, []
    for question, qtype, doc_kw, text_kw in QA30:
        res = index.search(question, qtype, k=3, boost=boost)
        hit = any(doc_kw in r["doc"] and text_kw in (r["snippet"] + r["unit"])
                  for r in res["results"])
        hits += int(hit)
        top1 = res["results"][0] if res["results"] else None
        details.append({"q": question, "hit": hit,
                        "top1": f"{top1['doc']}/{top1['unit']}" if top1 else None})
    rate = hits / len(QA30)
    tag = "부스트ON" if boost else "부스트OFF"
    print(f"  [{index.backend}/{tag}] top-3 적중 {hits}/{len(QA30)} = {rate:.0%}")
    return {"backend": index.backend, "boost": boost, "hit_rate": round(rate, 4),
            "hits": hits, "n": len(QA30), "details": details}
